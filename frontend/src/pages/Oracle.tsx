// ─── Markdown renderer ──────────────────────────────────────────────
function renderMarkdown(text: string): string {
  if (!text) return '';
  let html = text;
  html = html.replace(/```(\w*)\n?([\s\S]*?)```/g, (_: string, _lang: string, code: string) =>
    `<pre><code>${code.replace(/</g, '&lt;').replace(/>/g, '&gt;')}</code></pre>`);
  html = html.replace(/`([^`]+)`/g, (_: string, code: string) => {
    const e = code.replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;');
    return `<code>${e}</code>`;
  });
  html = html.replace(/^### (.+)$/gm, '<h3>$1</h3>');
  html = html.replace(/^## (.+)$/gm, '<h2>$1</h2>');
  html = html.replace(/^# (.+)$/gm, '<h1>$1</h1>');
  html = html.replace(/\*\*\*(.+?)\*\*\*/g, '<strong><em>$1</em></strong>');
  html = html.replace(/\*\*(.+?)\*\*/g, '<strong>$1</strong>');
  html = html.replace(/\*(.+?)\*/g, '<em>$1</em>');
  html = html.replace(/^[-*] (.+)$/gm, '<li>$1</li>');
  html = html.replace(/((?:<li>.*<\/li>\n?)+)/g, '<ul>$1</ul>');
  html = html.replace(/\n\n/g, '<br><br>');
  html = html.replace(/\n/g, '<br>');
  html = html.replace(/<br>(<\/?(?:h[1-3]|ul|ol|li|pre)>)/g, '$1');
  html = html.replace(/(<\/?(?:h[1-3]|ul|ol|li|pre)>)<br>/g, '$1');
  return DOMPurify.sanitize(html, { ADD_TAGS: ['h1', 'h2', 'h3', 'code', 'pre'], ADD_ATTR: ['class'] });
}

// ─── Parse [[[ACTION:...]]] tags ─────────────────────────────────────
function parseActions(text: string): { cleanText: string; actions: any[] } {
  const actions: any[] = [];
  const cleanText = text.replace(/\[\[\[ACTION:(.*?)\]\]\]/g, (_: string, actionStr: string) => {
    const parts = actionStr.split(':');
    const type = parts[0];
    const params = parts.slice(1);
    let label = '', icon = '';
    switch (type) {
      case 'alert': icon = '⚡'; label = `Set ${params[0]} alert at $${params[1]}`; break;
      case 'watchlist': icon = '👁️'; label = `Add ${params[0]} to watchlist`; break;
      case 'position': icon = '➕'; label = `Add ${params[1]} ${params[0]} @ $${params[2]}`; break;
      default: return '';
    }
    actions.push({ type, params, label, icon });
    return '';
  });
  return { cleanText, actions };
}

// ─── Parse <<<Q1|||Q2>>> suggestions ────────────────────────────────
function parseSuggestions(text: string): string[] {
  const match = text.match(/<<<(.+?)>>>/);
  if (!match) return [];
  return match[1].split('|||').map(q => q.trim()).filter(Boolean);
}

