// ─── ConversationsPanel ─────────────────────────────────────────────────
function ConversationsPanel({ currentId, onLoad, onClose }: { currentId?: number; onLoad: (conv: any) => void; onClose: () => void }) {
  const [convs, setConvs] = useState<Conversation[]>([]);
  const [loading, setLoading] = useState(true);

  useEffect(() => { loadConvs(); }, []);

  const loadConvs = async () => {
    try {
      const r = await fetch('/api/ai/conversations', { headers: { Authorization: `Bearer ${auth.getToken()}` } });
      setConvs(await r.json());
    } catch {}
    setLoading(false);
  };

  const del = async (id: number, e: React.MouseEvent) => {
    e.stopPropagation();
    if (!confirm('Delete this conversation?')) return;
    await fetch(`/api/ai/conversations/${id}`, { method: 'DELETE', headers: { Authorization: `Bearer ${auth.getToken()}` } });
    setConvs(cs => cs.filter(c => c.id !== id));
  };

  const load = async (id: number) => {
    try {
      const r = await fetch(`/api/ai/conversations/${id}`, { headers: { Authorization: `Bearer ${auth.getToken()}` } });
      const conv = await r.json();
      onLoad(conv);
      onClose();
    } catch (e: any) { toast.error('Failed to load conversation'); }
  };

  return (
    <div className="fixed inset-0 z-50 flex">
      <div className="flex-1" onClick={onClose} />
      <div className="w-[340px] bg-[#0d0f14] border-l border-white/10 flex flex-col h-full">
        <div className="flex items-center justify-between px-5 py-4 border-b border-white/10">
          <h3 className="text-white font-semibold">Conversations</h3>
          <button onClick={onClose} className="text-gray-500 hover:text-white"><X className="w-5 h-5" /></button>
        </div>
        <div className="flex-1 overflow-y-auto">
          {loading ? <div className="text-gray-500 text-sm text-center py-8">Loading...</div> :
           convs.length === 0 ? <div className="text-gray-500 text-sm text-center py-8">No conversations yet</div> :
           convs.map(c => (
            <div key={c.id} onClick={() => load(c.id)}
              className={`flex items-start justify-between p-4 border-b border-white/5 cursor-pointer hover:bg-white/5 transition-colors ${currentId === c.id ? 'bg-white/5' : ''}`}>
              <div className="flex-1 min-w-0">
                <div className="text-white text-sm font-medium truncate">{c.title || 'Untitled'}</div>
                <div className="text-gray-500 text-xs mt-0.5">{new Date(c.updated_at || c.created_at).toLocaleDateString()}</div>
              </div>
              <button onClick={(e) => del(c.id, e)} className="text-gray-600 hover:text-red-400 ml-2 mt-0.5">
                <Trash2 className="w-3.5 h-3.5" />
              </button>
            </div>
          ))}
        </div>
      </div>
    </div>
  );
}

