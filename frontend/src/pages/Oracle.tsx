// ─── API helpers (raw fetch for SSE) ─────────────────────────────────
async function fetchSSE(path: string, body: any, onChunk: (text: string) => void, onMeta?: (data: any) => void): Promise<{ rawText: string; usage?: any }> {
  const token = auth.getToken();
  const res = await fetch(`/api${path}`, {
    method: 'POST',
    headers: { 'Content-Type': 'application/json', ...(token ? { Authorization: `Bearer ${token}` } : {}) },
    body: JSON.stringify(body),
  });
  if (res.status === 401) { auth.clearSession(); window.location.href = '/login'; throw new Error('Unauthorized'); }
  if (!res.ok) { const t = await res.text(); throw new Error(t || `HTTP ${res.status}`); }

  const reader = res.body!.getReader();
  const decoder = new TextDecoder();
  let buf = '', rawText = '', usage: any;

  while (true) {
    const { done, value } = await reader.read();
    if (done) break;
    buf += decoder.decode(value, { stream: true });
    const lines = buf.split('\n');
    buf = lines.pop() || '';
    for (const line of lines) {
      const t = line.trim();
      if (!t.startsWith('data: ')) continue;
      try {
        const d = JSON.parse(t.slice(6));
        if (d.type === 'meta') onMeta?.(d);
        if (d.type === 'chunk' && d.content) { rawText += d.content; onChunk(rawText); }
        if (d.type === 'error') throw new Error(d.error || 'Stream error');
        if (d.type === 'done') usage = d.usage;
      } catch {}
    }
  }
  return { rawText, usage };
}

