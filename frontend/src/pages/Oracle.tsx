// ─── MessageBubble ─────────────────────────────────────────────────────
function MessageBubble({ msg, onAction, onPdf }: { msg: Msg; onAction: (action: any) => void; onPdf: (content: string) => void }) {
  const isUser = msg.role === 'user';
  const { cleanText, actions } = msg.role === 'assistant' && !msg.streaming
    ? parseActions(msg.content.replace(/<<<.+?>>>/g, ''))
    : { cleanText: msg.content, actions: [] };

  return (
    <div className={`flex gap-3 ${isUser ? 'flex-row-reverse' : ''} group`}>
      <div className={`w-8 h-8 rounded-lg flex items-center justify-center flex-shrink-0 ${
        isUser ? 'bg-gradient-to-br from-blue-500 to-purple-600' : 'bg-gradient-to-br from-purple-500 to-pink-600'
      }`}>
        {isUser ? <User className="w-4 h-4 text-white" /> : <Bot className="w-4 h-4 text-white" />}
      </div>
      <div className={`max-w-[75%] ${isUser ? 'items-end' : 'items-start'} flex flex-col gap-1`}>
        <div className={`px-4 py-3 rounded-xl text-sm leading-relaxed ${
          isUser
            ? 'bg-gradient-to-br from-blue-500/20 to-purple-600/20 border border-blue-500/30 text-white whitespace-pre-wrap'
            : 'bg-gradient-to-br from-[#1a1d29] to-[#14161f] border border-white/10 text-gray-200'
        }`}>
          {msg.streaming ? <TypingDots /> : (
            isUser
              ? msg.content
              : <div dangerouslySetInnerHTML={{ __html: renderMarkdown(cleanText.replace(/<<<.+?>>>/g, '')) }} className="prose-sm prose-invert" />
          )}
        </div>
        {/* Action buttons */}
        {actions.length > 0 && (
          <div className="flex flex-wrap gap-2 mt-1">
            {actions.map((a: any, i: number) => (
              <button key={i} onClick={() => onAction(a)}
                className="flex items-center gap-1.5 px-3 py-1.5 bg-amber-500/10 border border-amber-500/30 rounded-lg text-amber-400 text-xs hover:bg-amber-500/20 transition-colors">
                {a.icon} {a.label}
              </button>
            ))}
          </div>
        )}
        {/* Message actions */}
        {msg.role === 'assistant' && !msg.streaming && msg.content && (
          <div className="flex items-center gap-1 opacity-0 group-hover:opacity-100 transition-opacity">
            <button onClick={() => onPdf(msg.content)}
              className="flex items-center gap-1 px-2 py-1 rounded text-gray-500 hover:text-gray-300 hover:bg-white/5 text-xs transition-colors">
              <FileText className="w-3 h-3" /> PDF
            </button>
            {msg.usage && (
              <span className="text-gray-600 text-xs px-2">{msg.usage.model?.split('/').pop()} · {msg.usage.durationMs ? `${(msg.usage.durationMs/1000).toFixed(1)}s` : ''}</span>
            )}
          </div>
        )}
      </div>
    </div>
  );
}

